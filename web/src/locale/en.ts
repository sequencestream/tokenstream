import { BASE_URL_NOTE, TROUBLESHOOTING, WEBSOCKET_NOTE, curlExamples } from '../docs/endpoints.ts'

function trouble(id: (typeof TROUBLESHOOTING)[number]['id']) {
  const note = TROUBLESHOOTING.find((item) => item.id === id)
  if (!note) throw new Error(`missing troubleshooting note ${id}`)
  return note
}

function exampleTitle(id: string) {
  const title = curlExamples().find((item) => item.id === id)?.title
  if (!title) throw new Error(`missing example ${id}`)
  return title
}

